import { createHash } from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const appRoot = fileURLToPath(new URL('../', import.meta.url))
const args = process.argv.slice(2)
const check = args.includes('--check')
const inputFlag = args.indexOf('--translations')
const translationsRoot = inputFlag < 0
  ? path.resolve(appRoot, '../../packages/client/locale/src/translations')
  : path.resolve(args[inputFlag + 1] ?? '')
const allowed = new Set(['--check', '--translations', inputFlag < 0 ? '' : args[inputFlag + 1]])
if (args.some(value => !allowed.has(value)) || (inputFlag >= 0 && !args[inputFlag + 1])) {
  throw new Error('Usage: node generate-desktop-translations.mjs [--check] [--translations DIRECTORY]')
}
const sourcePath = path.join(appRoot, 'src/locale.ts')
const source = ts.createSourceFile(sourcePath, fs.readFileSync(sourcePath, 'utf8'), ts.ScriptTarget.Latest, true)
let english
function visit(node) {
  if (ts.isVariableDeclaration(node) && ts.isIdentifier(node.name) && node.name.text === 'en') {
    let value = node.initializer
    while (value && (ts.isAsExpression(value) || ts.isSatisfiesExpression(value))) value = value.expression
    if (!value || !ts.isObjectLiteralExpression(value)) throw new Error('Desktop English dictionary must be a literal object')
    english = {}
    for (const property of value.properties) {
      if (!ts.isPropertyAssignment(property) || !ts.isStringLiteralLike(property.initializer)
        || !(ts.isIdentifier(property.name) || ts.isStringLiteralLike(property.name))) {
        throw new Error('Desktop English dictionary must contain string properties')
      }
      english[property.name.text] = property.initializer.text
    }
  }
  ts.forEachChild(node, visit)
}
visit(source)
if (!english || Object.keys(english).length === 0) throw new Error('Desktop English dictionary was not found')
const languages = ['zh-Hant', 'ja', 'ko', 'de', 'fr', 'es', 'pt']
const placeholders = text => [...text.matchAll(/\{[^{}]+\}/gu)].map(match => match[0]).sort()
const dictionaries = Object.fromEntries(languages.map(language => {
  const translations = JSON.parse(fs.readFileSync(path.join(translationsRoot, `${language}.json`), 'utf8'))
  return [language, Object.fromEntries(Object.entries(english).map(([key, text]) => {
    const translated = translations[text]
    if (typeof translated !== 'string' || (text.trim() !== '' && translated.trim() === '')) {
      throw new Error(`Missing ${language} Desktop translation: ${key}`)
    }
    if (JSON.stringify(placeholders(text)) !== JSON.stringify(placeholders(translated))) {
      throw new Error(`Mismatched ${language} Desktop placeholders: ${key}`)
    }
    return [key, translated]
  }))]
}))
const digest = createHash('sha256').update(JSON.stringify(english)).digest('hex')
const expected = `/** Native Desktop dictionaries generated by scripts/generate-desktop-translations.mjs. */
import type { DesktopMessages } from './locale.ts'

/** Fingerprint of the English messages used to generate the translations. */
export const DESKTOP_ENGLISH_COPY_HASH = '${digest}'

/** Complete native dictionaries selected by the Desktop locale resolver. */
export const extraDesktopMessages = ${JSON.stringify(dictionaries, null, 2)} as const satisfies Readonly<Record<
  'zh-Hant' | 'ja' | 'ko' | 'de' | 'fr' | 'es' | 'pt', DesktopMessages
>>
`
const outputPath = path.join(appRoot, 'src/locale-extra.ts')
if (check) {
  if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, 'utf8') !== expected) {
    throw new Error('Desktop translations are stale; run node apps/desktop/scripts/generate-desktop-translations.mjs')
  }
  console.log(`Desktop translations are current: ${languages.length} languages, ${Object.keys(english).length} messages each`)
} else {
  fs.writeFileSync(outputPath, expected)
  console.log(`Generated ${languages.length} Desktop dictionaries with ${Object.keys(english).length} messages each`)
}
